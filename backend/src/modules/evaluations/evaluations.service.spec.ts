import { Test, TestingModule } from '@nestjs/testing';
import { EvaluationsService } from './evaluations.service';
import { InferenceService } from '../inference/inference.service';
import { NotFoundException } from '@nestjs/common';

describe('EvaluationsService', () => {
  let service: EvaluationsService;
  let inferenceService: jest.Mocked<Partial<InferenceService>>;

  beforeEach(async () => {
    inferenceService = {
      chatCompletion: jest.fn().mockImplementation(async (req: any) => {
        if (req.model === 'judge-model' || req.model === 'deepseek-r1-70b') {
          return {
            id: 'chatcmpl-judge',
            object: 'chat.completion',
            created: Math.floor(Date.now() / 1000),
            model: req.model,
            choices: [
              {
                index: 0,
                message: {
                  role: 'assistant',
                  content: JSON.stringify({
                    winner: 'modelA',
                    scoreA: { accuracy: 9, reasoning: 9, adherence: 9, overall: 9.0 },
                    scoreB: { accuracy: 7, reasoning: 7, adherence: 7, overall: 7.0 },
                    reasoning: 'Model A provided a cleaner, more complete solution.',
                  }),
                },
                finish_reason: 'stop',
              },
            ],
            usage: { prompt_tokens: 300, completion_tokens: 60, total_tokens: 360 },
          };
        }

        return {
          id: `chatcmpl-${req.model}`,
          object: 'chat.completion',
          created: Math.floor(Date.now() / 1000),
          model: req.model,
          choices: [
            {
              index: 0,
              message: {
                role: 'assistant',
                content: `Response generated by ${req.model} to prompt.`,
              },
              finish_reason: 'stop',
            },
          ],
          usage: { prompt_tokens: 50, completion_tokens: 40, total_tokens: 90 },
        };
      }),
    };

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        EvaluationsService,
        {
          provide: InferenceService,
          useValue: inferenceService,
        },
      ],
    }).compile();

    service = module.get<EvaluationsService>(EvaluationsService);
  });

  it('should be defined', () => {
    expect(service).toBeDefined();
  });

  describe('listBenchmarkSuites', () => {
    it('should return predefined benchmark suites', () => {
      const suites = service.listBenchmarkSuites();
      expect(suites.length).toBeGreaterThanOrEqual(3);
      expect(suites.some((s) => s.id === 'coding_bench')).toBe(true);
      expect(suites.some((s) => s.id === 'reasoning_bench')).toBe(true);
      expect(suites.some((s) => s.id === 'safety_guardrails_bench')).toBe(true);
    });

    it('should return suite by ID or throw 404', () => {
      const suite = service.getBenchmarkSuite('coding_bench');
      expect(suite.name).toBe('Software Engineering & Algorithms');
      expect(() => service.getBenchmarkSuite('nonexistent_suite')).toThrow(NotFoundException);
    });
  });

  describe('runEvaluation', () => {
    it('should execute benchmark across Model A and Model B and aggregate judge scores', async () => {
      const result = await service.runEvaluation({
        modelA: 'llama-3.3-70b',
        modelB: 'qwen-2.5-coder-32b',
        judgeModel: 'deepseek-r1-70b',
        benchmarkSuiteId: 'coding_bench',
      });

      expect(result.id).toMatch(/^eval-/);
      expect(result.modelA).toBe('llama-3.3-70b');
      expect(result.modelB).toBe('qwen-2.5-coder-32b');
      expect(result.totalSamples).toBe(3);
      expect(result.sampleResults).toHaveLength(3);

      expect(result.summary.winsA).toBe(3);
      expect(result.summary.winRateA).toBe(100);
      expect(result.summary.avgOverallScoreA).toBe(9.0);
      expect(result.summary.avgOverallScoreB).toBe(7.0);

      expect(result.sampleResults[0].judge.winner).toBe('modelA');
      expect(result.sampleResults[0].responseA.content).toContain('llama-3.3-70b');
      expect(result.sampleResults[0].responseB.content).toContain('qwen-2.5-coder-32b');
    });

    it('should handle custom sample overrides', async () => {
      const result = await service.runEvaluation({
        modelA: 'model-x',
        modelB: 'model-y',
        benchmarkSuiteId: 'coding_bench',
        samples: [
          {
            id: 'custom-1',
            title: 'Custom Test',
            prompt: 'Test prompt',
            expectedCriteria: 'Test criteria',
            category: 'general',
          },
        ],
      });

      expect(result.totalSamples).toBe(1);
      expect(result.sampleResults[0].sampleTitle).toBe('Custom Test');
    });
  });
});
