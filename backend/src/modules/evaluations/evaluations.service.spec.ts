import { Test, TestingModule } from '@nestjs/testing';
import { EvaluationsService } from './evaluations.service';
import { InferenceService } from '../inference/inference.service';
import { NotFoundException, UnprocessableEntityException } from '@nestjs/common';

describe('EvaluationsService', () => {
  let service: EvaluationsService;
  let inferenceService: jest.Mocked<Partial<InferenceService>>;

  beforeEach(async () => {
    inferenceService = {
      chatCompletion: jest.fn().mockImplementation(async (req: any) => {
        if (req.model === 'judge-model' || req.model === 'deepseek-r1-70b') {
          return {
            id: 'chatcmpl-judge',
            object: 'chat.completion',
            created: Math.floor(Date.now() / 1000),
            model: req.model,
            choices: [
              {
                index: 0,
                message: {
                  role: 'assistant',
                  content: JSON.stringify({
                    winner: 'modelA',
                    scoreA: { accuracy: 9, reasoning: 9, adherence: 9, overall: 9.0 },
                    scoreB: { accuracy: 7, reasoning: 7, adherence: 7, overall: 7.0 },
                    reasoning: 'Model A provided a cleaner, more complete solution.',
                  }),
                },
                finish_reason: 'stop',
              },
            ],
            usage: { prompt_tokens: 300, completion_tokens: 60, total_tokens: 360 },
          };
        }

        return {
          id: `chatcmpl-${req.model}`,
          object: 'chat.completion',
          created: Math.floor(Date.now() / 1000),
          model: req.model,
          choices: [
            {
              index: 0,
              message: {
                role: 'assistant',
                content: `Response generated by ${req.model} to prompt.`,
              },
              finish_reason: 'stop',
            },
          ],
          usage: { prompt_tokens: 50, completion_tokens: 40, total_tokens: 90 },
        };
      }),
    };

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        EvaluationsService,
        {
          provide: InferenceService,
          useValue: inferenceService,
        },
      ],
    }).compile();

    service = module.get<EvaluationsService>(EvaluationsService);
  });

  it('should be defined', () => {
    expect(service).toBeDefined();
  });

  describe('listBenchmarkSuites', () => {
    it('should return predefined benchmark suites', () => {
      const suites = service.listBenchmarkSuites();
      expect(suites.length).toBeGreaterThanOrEqual(3);
      expect(suites.some((s) => s.id === 'coding_bench')).toBe(true);
      expect(suites.some((s) => s.id === 'reasoning_bench')).toBe(true);
      expect(suites.some((s) => s.id === 'safety_guardrails_bench')).toBe(true);
    });

    it('should return suite by ID or throw 404', () => {
      const suite = service.getBenchmarkSuite('coding_bench');
      expect(suite.name).toBe('Software Engineering & Algorithms');
      expect(() => service.getBenchmarkSuite('nonexistent_suite')).toThrow(NotFoundException);
    });
  });

  describe('runEvaluation', () => {
    it('should execute benchmark across Model A and Model B and aggregate judge scores', async () => {
      const result = await service.runEvaluation({
        modelA: 'llama-3.3-70b',
        modelB: 'qwen-2.5-coder-32b',
        judgeModel: 'deepseek-r1-70b',
        benchmarkSuiteId: 'coding_bench',
      });

      expect(result.id).toMatch(/^eval-/);
      expect(result.modelA).toBe('llama-3.3-70b');
      expect(result.modelB).toBe('qwen-2.5-coder-32b');
      expect(result.totalSamples).toBe(3);
      expect(result.sampleResults).toHaveLength(3);

      expect(result.summary.winsA).toBe(3);
      expect(result.summary.winRateA).toBe(100);
      expect(result.summary.avgOverallScoreA).toBe(9.0);
      expect(result.summary.avgOverallScoreB).toBe(7.0);

      expect(result.sampleResults[0].judge.winner).toBe('modelA');
      expect(result.sampleResults[0].responseA.content).toContain('llama-3.3-70b');
      expect(result.sampleResults[0].responseB.content).toContain('qwen-2.5-coder-32b');
    });

    it('should handle custom sample overrides', async () => {
      const result = await service.runEvaluation({
        modelA: 'model-x',
        modelB: 'model-y',
        benchmarkSuiteId: 'coding_bench',
        samples: [
          {
            id: 'custom-1',
            title: 'Custom Test',
            prompt: 'Test prompt',
            expectedCriteria: 'Test criteria',
            category: 'general',
          },
        ],
      });

      expect(result.totalSamples).toBe(1);
      expect(result.sampleResults[0].sampleTitle).toBe('Custom Test');
    });
  });

  describe('getLeaderboard', () => {
    it('should return ranked models with Elo ratings and win rates', () => {
      const leaderboard = service.getLeaderboard();
      expect(leaderboard.length).toBeGreaterThanOrEqual(6);
      expect(leaderboard[0].rank).toBe(1);
      expect(leaderboard[0].elo).toBeGreaterThanOrEqual(leaderboard[1].elo);
      expect(leaderboard.some((m) => m.model === 'deepseek-r1-70b')).toBe(true);
      expect(leaderboard.some((m) => m.model === 'llama-3.3-70b')).toBe(true);
    });
  });

  describe('getHistory & getHistoryById', () => {
    it('should return seeded and dynamic evaluation runs', async () => {
      const initialHistory = service.getHistory();
      expect(initialHistory.length).toBeGreaterThanOrEqual(3);

      const firstRun = service.getHistoryById(initialHistory[0].id);
      expect(firstRun.id).toBe(initialHistory[0].id);
      expect(() => service.getHistoryById('nonexistent-id')).toThrow(NotFoundException);

      // Run new eval and verify it prepends to history
      const newRun = await service.runEvaluation({
        modelA: 'llama-3.3-70b',
        modelB: 'deepseek-r1-70b',
        benchmarkSuiteId: 'reasoning_bench',
      });

      const updatedHistory = service.getHistory();
      expect(updatedHistory[0].id).toBe(newRun.id);
    });
  });

  describe('generateSyntheticSuite', () => {
    it('should generate a benchmark suite from domain description', async () => {
      const suite = await service.generateSyntheticSuite({
        domain: 'Kubernetes Operator Concurrency & Mutexes',
        category: 'coding',
        testCount: 3,
      });

      expect(suite.id).toMatch(/^synthetic_/);
      expect(suite.name).toContain('Kubernetes Operator Concurrency');
      expect(suite.samples).toHaveLength(3);
      expect(suite.category).toBe('coding');

      // Verify it was added to active suites
      const activeSuites = service.listBenchmarkSuites();
      expect(activeSuites.some((s) => s.id === suite.id)).toBe(true);
    });
  });

  describe('assertQualityGate', () => {
    it('should approve deployment when candidate meets all thresholds', async () => {
      const gate = await service.assertQualityGate({
        candidateModel: 'llama-3.3-70b',
        baselineModel: 'qwen-2.5-coder-32b',
        benchmarkSuiteId: 'coding_bench',
        minWinRate: 50,
        minOverallScore: 8.0,
        minAccuracyScore: 7.0,
        maxLatencyMs: 3000,
      });

      expect(gate.passed).toBe(true);
      expect(gate.deploymentApproved).toBe(true);
      expect(gate.violations).toHaveLength(0);
      expect(gate.metrics.winRate).toBeGreaterThanOrEqual(50);
    });

    it('should detect violations and block deployment when below threshold', async () => {
      const gate = await service.assertQualityGate({
        candidateModel: 'llama-3.3-70b',
        baselineModel: 'qwen-2.5-coder-32b',
        benchmarkSuiteId: 'coding_bench',
        minWinRate: 100, // Impossibly high threshold
        minOverallScore: 9.9, // Higher than score 9.0
        failOnThreshold: false,
      });

      expect(gate.passed).toBe(false);
      expect(gate.deploymentApproved).toBe(false);
      expect(gate.violations.length).toBeGreaterThan(0);
    });

    it('should throw UnprocessableEntityException when failOnThreshold is true and violations occur', async () => {
      await expect(
        service.assertQualityGate({
          candidateModel: 'llama-3.3-70b',
          baselineModel: 'qwen-2.5-coder-32b',
          benchmarkSuiteId: 'coding_bench',
          minWinRate: 100,
          minOverallScore: 9.9,
          failOnThreshold: true,
        })
      ).rejects.toThrow(UnprocessableEntityException);
    });
  });

  describe('detectModelDrift', () => {
    it('should return drift trajectory for model with historical runs', () => {
      const drift = service.detectModelDrift('llama-3.3-70b');
      expect(drift.model).toBe('llama-3.3-70b');
      expect(drift.historicalRunsCount).toBeGreaterThanOrEqual(2);
      expect(['STABLE', 'DEGRADED', 'IMPROVED']).toContain(drift.status);
      expect(drift.recommendation).toBeDefined();
    });

    it('should return INSUFFICIENT_DATA for un-evaluated models', () => {
      const drift = service.detectModelDrift('unseen-model-xyz');
      expect(drift.status).toBe('INSUFFICIENT_DATA');
      expect(drift.driftDetected).toBe(false);
    });
  });

  describe('exportAuditReport', () => {
    it('should generate markdown audit certificate with compliance hash', () => {
      const history = service.getHistory();
      const exportReport = service.exportAuditReport(history[0].id, 'markdown');

      expect(exportReport.runId).toBe(history[0].id);
      expect(exportReport.exportFormat).toBe('markdown');
      expect(exportReport.content).toContain('YOYO LLM-as-a-Judge Formal Audit Certificate');
      expect(exportReport.complianceHash).toHaveLength(64); // SHA-256
    });

    it('should generate JSON and CSV audit formats', () => {
      const history = service.getHistory();
      const jsonReport = service.exportAuditReport(history[0].id, 'json');
      expect(JSON.parse(jsonReport.content).runId).toBe(history[0].id);

      const csvReport = service.exportAuditReport(history[0].id, 'csv');
      expect(csvReport.content).toContain('SampleID,SampleTitle,ModelA');
    });
  });
});
